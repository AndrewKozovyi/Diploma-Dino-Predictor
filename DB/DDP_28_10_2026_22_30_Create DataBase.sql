/*
    Dino Predictor: DB creation

    Conventions:
      - all dates are UTC;
      - PredictHistoryRequests.Id will be generated by the API (UUIDv7);
      - the predicted species and its confidence are the PredictHistoryResults row with Rank = 1;
*/

SET ANSI_NULLS ON;
SET QUOTED_IDENTIFIER ON;
SET XACT_ABORT ON;
BEGIN TRANSACTION;

IF OBJECT_ID(N'dbo.DinoTypes', N'U') IS NULL
CREATE TABLE dbo.DinoTypes (
    Id TINYINT NOT NULL,
    Code VARCHAR(50) NOT NULL,
    CONSTRAINT PK_DinoTypes PRIMARY KEY (Id),
    CONSTRAINT UQ_DinoTypes_Code UNIQUE (Code)
);

IF OBJECT_ID(N'dbo.DinoTypeTranslations', N'U') IS NULL
CREATE TABLE dbo.DinoTypeTranslations (
    DinoTypeId TINYINT NOT NULL,
    Culture VARCHAR(10) NOT NULL,
    Name NVARCHAR(100) NOT NULL,
    CONSTRAINT PK_DinoTypeTranslations PRIMARY KEY (DinoTypeId, Culture),
    CONSTRAINT FK_DinoTypeTranslations_DinoTypes FOREIGN KEY (DinoTypeId)
        REFERENCES dbo.DinoTypes (Id)
);

IF OBJECT_ID(N'dbo.PredictHistoryRequests', N'U') IS NULL
CREATE TABLE dbo.PredictHistoryRequests (
    Id UNIQUEIDENTIFIER NOT NULL,
    CreatedAt DATETIME2(3) NOT NULL
        CONSTRAINT DF_PredictHistoryRequests_CreatedAt DEFAULT (SYSUTCDATETIME()),
    ImagePublicId VARCHAR(255) NOT NULL,
    CamImagePublicId VARCHAR(255) NULL,
    OriginalFileName NVARCHAR(255) NOT NULL,
    ModelVersion VARCHAR(64) NOT NULL,
    ProcessingMs INT NOT NULL,
    CONSTRAINT PK_PredictHistoryRequests PRIMARY KEY (Id),
    CONSTRAINT CK_PredictHistoryRequests_ProcessingMs CHECK (ProcessingMs >= 0)
);

IF OBJECT_ID(N'dbo.PredictHistoryResults', N'U') IS NULL
CREATE TABLE dbo.PredictHistoryResults (
    RequestId UNIQUEIDENTIFIER NOT NULL,
    DinoTypeId TINYINT NOT NULL,
    Rank TINYINT NOT NULL,
    Probability DECIMAL(5, 4) NOT NULL,
    CONSTRAINT PK_PredictHistoryResults PRIMARY KEY (RequestId, DinoTypeId),
    CONSTRAINT FK_PredictHistoryResults_PredictHistoryRequests FOREIGN KEY (RequestId)
        REFERENCES dbo.PredictHistoryRequests (Id) ON DELETE CASCADE,
    CONSTRAINT FK_PredictHistoryResults_DinoTypes FOREIGN KEY (DinoTypeId)
        REFERENCES dbo.DinoTypes (Id),
    CONSTRAINT UQ_PredictHistoryResults_RequestId_Rank UNIQUE (RequestId, Rank),
    CONSTRAINT CK_PredictHistoryResults_Rank CHECK (Rank BETWEEN 1 AND 5),
    CONSTRAINT CK_PredictHistoryResults_Probability CHECK (Probability BETWEEN 0 AND 1)
);

-- "Last 10" and paging of the history
IF NOT EXISTS (
    SELECT 1 FROM sys.indexes
    WHERE name = N'IX_PredictHistoryRequests_CreatedAt'
      AND object_id = OBJECT_ID(N'dbo.PredictHistoryRequests')
)
CREATE INDEX IX_PredictHistoryRequests_CreatedAt
    ON dbo.PredictHistoryRequests (CreatedAt DESC);

-- History filter by predicted species (top-1 only)
IF NOT EXISTS (
    SELECT 1 FROM sys.indexes
    WHERE name = N'IX_PredictHistoryResults_Top1_DinoTypeId'
      AND object_id = OBJECT_ID(N'dbo.PredictHistoryResults')
)
CREATE INDEX IX_PredictHistoryResults_Top1_DinoTypeId
    ON dbo.PredictHistoryResults (DinoTypeId, RequestId)
    INCLUDE (Probability)
    WHERE Rank = 1;

COMMIT TRANSACTION;
